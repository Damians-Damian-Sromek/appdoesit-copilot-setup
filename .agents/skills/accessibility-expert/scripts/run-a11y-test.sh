#!/bin/bash
# Run comprehensive accessibility test with Playwright + Lighthouse
# Tests apps in their ACTIVE state (with user interaction and results visible)
#
# Usage:
#   ./run-a11y-test.sh --app calculator           # Test single app
#   ./run-a11y-test.sh --app calculator --screenshots  # Also capture screenshots
#   ./run-a11y-test.sh --all                      # Test all apps
#
# This script:
# 1. Launches Playwright to interact with the app
# 2. Puts the app in "active" state (with results visible)
# 3. Runs Lighthouse accessibility audit
# 4. Captures screenshots for visual verification

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
# Per-clone web port (multi-clone support): default to this clone's host port.
# shellcheck source=instance-env.sh
source "$PROJECT_ROOT/scripts/instance-env.sh"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

# Default values
APP_SLUG=""
OUTPUT_DIR="./var/tmp/accessibility"
CAPTURE_SCREENSHOTS=false
TEST_ALL=false
BASE_URL="${BASE_URL:-http://localhost:${WEB_PORT}}"
NETWORK="host"

# Parse arguments
while [[ $# -gt 0 ]]; do
    case $1 in
        --app)
            APP_SLUG="$2"
            shift 2
            ;;
        --all)
            TEST_ALL=true
            shift
            ;;
        --screenshots)
            CAPTURE_SCREENSHOTS=true
            shift
            ;;
        --output)
            OUTPUT_DIR="$2"
            shift 2
            ;;
        --docker)
            BASE_URL="http://web"
            NETWORK="$DEV_NETWORK"
            shift
            ;;
        --help|-h)
            echo "Accessibility Test Runner"
            echo ""
            echo "Usage:"
            echo "  ./run-a11y-test.sh --app <slug>     Test single app"
            echo "  ./run-a11y-test.sh --all            Test all apps"
            echo ""
            echo "Options:"
            echo "  --app <slug>      App to test (e.g., calculator, json-formatter)"
            echo "  --all             Test all apps"
            echo "  --screenshots     Capture screenshots for visual verification"
            echo "  --output <dir>    Output directory (default: ./accessibility-reports)"
            echo "  --docker          Use Docker network (for testing inside containers)"
            echo "  --help, -h        Show this help"
            exit 0
            ;;
        *)
            echo -e "${RED}Unknown option: $1${NC}"
            exit 1
            ;;
    esac
done

# Validate arguments
if [[ -z "$APP_SLUG" && "$TEST_ALL" != "true" ]]; then
    echo -e "${RED}Error: --app <slug> or --all required${NC}"
    echo "Use --help for usage information"
    exit 1
fi

# Create output directory
mkdir -p "$OUTPUT_DIR"

# Get list of apps if testing all
if [[ "$TEST_ALL" == "true" ]]; then
    echo -e "${CYAN}Discovering apps...${NC}"
    APPS=$(curl -s "$BASE_URL" 2>/dev/null | grep -oP 'data-app-slug="\K[^"]+' | sort -u)
    if [[ -z "$APPS" ]]; then
        echo -e "${RED}Error: Could not discover apps. Is the server running?${NC}"
        exit 1
    fi
    echo -e "${GREEN}Found apps: $(echo $APPS | tr '\n' ' ')${NC}"
else
    APPS="$APP_SLUG"
fi

# Create Playwright test file for active state testing.
# NOTE: Playwright config in this repo uses `testDir: ./tests/e2e`, and the
# CLI treats provided args as globs/regex matched within `testDir`.
# Therefore this generated spec must live under `tests/e2e/`.
PLAYWRIGHT_TEST_FILE_REL="tests/e2e/_a11y-active-state-test.spec.js"
PLAYWRIGHT_TEST_FILE="$PROJECT_ROOT/$PLAYWRIGHT_TEST_FILE_REL"

cat > "$PLAYWRIGHT_TEST_FILE" << 'PLAYWRIGHT_EOF'
// Accessibility Active State Test
// Generated by run-a11y-test.sh

const { test, expect } = require('@playwright/test');

// App-specific activation functions
const APP_ACTIVATORS = {
    'calculator': async (page) => {
        // Enter a calculation: 7 + 3 = 10
        await page.click('button:has-text("7")').catch(() => {});
        await page.click('button:has-text("+")').catch(() => {});
        await page.click('button:has-text("3")').catch(() => {});
        await page.click('button:has-text("=")').catch(() => {});
    },

    'word-counter': async (page) => {
        const textarea = await page.$('textarea, #text-input, [data-testid="text-input"]');
        if (textarea) {
            await textarea.fill('This is sample text for testing. It has multiple sentences. The word counter should display statistics for this content.');
        }
    },

    'password-generator': async (page) => {
        const generateBtn = await page.$('#generate-btn, button:has-text("Generate"), [data-testid="generate"]');
        if (generateBtn) await generateBtn.click();
    },

    'json-formatter': async (page) => {
        const input = await page.$('#json-input, textarea, [data-testid="json-input"]');
        if (input) {
            await input.fill('{"name": "Test", "value": 123, "nested": {"key": "value"}}');
        }
        const formatBtn = await page.$('#format-btn, button:has-text("Format"), [data-testid="format"]');
        if (formatBtn) await formatBtn.click();
    },

    'unit-converter': async (page) => {
        const input = await page.$('#input-value, input[type="number"], [data-testid="input-value"]');
        if (input) await input.fill('100');
    },

    'bmi-calculator': async (page) => {
        const height = await page.$('#height, [data-testid="height"], input[name="height"]');
        const weight = await page.$('#weight, [data-testid="weight"], input[name="weight"]');
        if (height) await height.fill('175');
        if (weight) await weight.fill('70');
        const calcBtn = await page.$('#calculate-btn, button:has-text("Calculate"), [data-testid="calculate"]');
        if (calcBtn) await calcBtn.click().catch(() => {});
    },

    'age-calculator': async (page) => {
        const birthDate = await page.$('#birth-date, input[type="date"], [data-testid="birth-date"]');
        if (birthDate) await birthDate.fill('1990-05-15');
    },

    'time-zone-converter': async (page) => {
        // Usually shows current time by default, but try to interact
        const sourceSelect = await page.$('#source-timezone, select:first-of-type');
        const targetSelect = await page.$('#target-timezone, select:last-of-type');
        if (sourceSelect) await sourceSelect.selectOption({ index: 1 }).catch(() => {});
        if (targetSelect) await targetSelect.selectOption({ index: 2 }).catch(() => {});
    },

    'text-case-converter': async (page) => {
        const input = await page.$('#text-input, textarea, [data-testid="text-input"]');
        if (input) await input.fill('Sample Text For CASE Conversion Testing');
    },

    'percentage-calculator': async (page) => {
        const value1 = await page.$('#value1, input:first-of-type, [data-testid="value1"]');
        const value2 = await page.$('#value2, input:nth-of-type(2), [data-testid="value2"]');
        if (value1) await value1.fill('25');
        if (value2) await value2.fill('100');
    },

    'alphabet-learning': async (page) => {
        // Click a letter button if available
        const letterBtn = await page.$('.letter-btn, button[data-letter]');
        if (letterBtn) await letterBtn.click().catch(() => {});
    }
};

// Generic activator for unknown apps
async function genericActivate(page) {
    // Try to find and fill the first input
    const input = await page.$('input[type="text"], input[type="number"], textarea');
    if (input) {
        await input.fill('Test input data');
    }

    // Try to find and click a primary button
    const btn = await page.$('button[type="submit"], button.primary, button:has-text("Calculate"), button:has-text("Generate"), button:has-text("Convert")');
    if (btn) {
        await btn.click().catch(() => {});
    }
}

// Helper to set theme
async function setTheme(page, theme) {
    await page.evaluate((t) => {
        document.documentElement.setAttribute('data-theme', t);
        localStorage.setItem('appdoesit-theme', t);
    }, theme);
    await page.waitForTimeout(150);
}

// Helper to activate app
async function activateApp(page, slug) {
    await page.waitForLoadState('networkidle');
    await page.waitForTimeout(200);

    const activator = APP_ACTIVATORS[slug] || genericActivate;
    await activator(page);

    await page.waitForTimeout(300); // Wait for UI updates
}

// Read test configuration from environment
const APPS_TO_TEST = (process.env.APPS_TO_TEST || '').split(',').filter(Boolean);
const BASE_URL = process.env.BASE_URL || 'http://localhost:8000';
const OUTPUT_DIR = process.env.OUTPUT_DIR || './accessibility-reports';
const CAPTURE_SCREENSHOTS = process.env.CAPTURE_SCREENSHOTS === 'true';

for (const slug of APPS_TO_TEST) {
    test.describe(`Accessibility: ${slug}`, () => {

        test(`${slug} - active state accessibility check`, async ({ page }) => {
            // Navigate to app
            await page.goto(`${BASE_URL}/apps/${slug}`);
            await page.waitForLoadState('domcontentloaded');

            // Wait for full render
            await page.waitForLoadState('networkidle');
            await page.waitForSelector('main', { state: 'visible', timeout: 5000 }).catch(() => {});

            // Activate the app
            await activateApp(page, slug);

            // Basic accessibility checks
            // 1. Check for skip link
            const skipLink = await page.$('a.skip-link, a[href^="#"]');
            expect(skipLink, 'Skip link should exist').toBeTruthy();

            // 2. Check for main landmark
            const main = await page.$('main, [role="main"]');
            expect(main, 'Main landmark should exist').toBeTruthy();

            // 3. Check for h1
            const h1 = await page.$('h1');
            expect(h1, 'H1 heading should exist').toBeTruthy();

            // 4. Check lang attribute
            const lang = await page.getAttribute('html', 'lang');
            expect(lang, 'HTML should have lang attribute').toBeTruthy();

            // 5. Check for form labels
            const inputs = await page.$$('input:not([type="hidden"]):not([type="submit"]):not([type="button"])');
            for (const input of inputs) {
                const id = await input.getAttribute('id');
                const ariaLabel = await input.getAttribute('aria-label');
                const ariaLabelledby = await input.getAttribute('aria-labelledby');

                if (id) {
                    const label = await page.$(`label[for="${id}"]`);
                    const hasLabel = label || ariaLabel || ariaLabelledby;
                    expect(hasLabel, `Input ${id} should have a label`).toBeTruthy();
                }
            }

            // 6. Check for button names
            const buttons = await page.$$('button');
            for (const button of buttons) {
                const text = await button.textContent();
                const ariaLabel = await button.getAttribute('aria-label');
                const hasName = (text && text.trim()) || ariaLabel;
                expect(hasName, 'All buttons should have accessible names').toBeTruthy();
            }

            // Capture screenshot if requested
            if (CAPTURE_SCREENSHOTS) {
                await page.screenshot({
                    path: `${OUTPUT_DIR}/${slug}-active-state.png`,
                    fullPage: true
                });
            }
        });

        if (CAPTURE_SCREENSHOTS) {
            test(`${slug} - theme screenshots`, async ({ page }) => {
                for (const theme of ['light', 'dark']) {
                    await page.goto(`${BASE_URL}/apps/${slug}`);
                    await activateApp(page, slug);
                    await setTheme(page, theme);

                    await page.screenshot({
                        path: `${OUTPUT_DIR}/${slug}-${theme}-active.png`,
                        fullPage: true
                    });
                }
            });

            test(`${slug} - mobile screenshot`, async ({ page }) => {
                await page.setViewportSize({ width: 375, height: 667 });
                await page.goto(`${BASE_URL}/apps/${slug}`);
                await activateApp(page, slug);

                await page.screenshot({
                    path: `${OUTPUT_DIR}/${slug}-mobile-active.png`,
                    fullPage: true
                });
            });

            test(`${slug} - localized screenshot (Spanish)`, async ({ page }) => {
                await page.goto(`${BASE_URL}/es/apps/${slug}`);
                await activateApp(page, slug);

                await page.screenshot({
                    path: `${OUTPUT_DIR}/${slug}-es-active.png`,
                    fullPage: true
                });
            });
        }
    });
}
PLAYWRIGHT_EOF

echo -e "${BLUE}========================================${NC}"
echo -e "${BLUE}Accessibility Test Runner${NC}"
echo -e "${BLUE}========================================${NC}"
echo ""

# Run tests for each app
for app in $APPS; do
    echo -e "${CYAN}Testing: $app${NC}"
    echo -e "${YELLOW}----------------------------------------${NC}"

    TIMESTAMP=$(date +%Y%m%d_%H%M%S)

    # Run Playwright accessibility tests
    echo -e "${GREEN}1. Running Playwright active-state tests...${NC}"

    SCREENSHOT_FLAG=""
    if [[ "$CAPTURE_SCREENSHOTS" == "true" ]]; then
        SCREENSHOT_FLAG="CAPTURE_SCREENSHOTS=true"
    fi

    docker run --rm \
        --network "$NETWORK" \
        -e BASE_URL="$BASE_URL" \
        -e SKIP_WEBSERVER=1 \
        -e APPS_TO_TEST="$app" \
        -e OUTPUT_DIR="/reports" \
        -e $SCREENSHOT_FLAG \
        -v "$PROJECT_ROOT":/app \
        -v "$(pwd)/$OUTPUT_DIR":/reports \
        -w /app \
        mcr.microsoft.com/playwright:v1.57.0-jammy \
        sh -c "npm install --silent 2>/dev/null && npx playwright test $PLAYWRIGHT_TEST_FILE_REL --reporter=list" 2>&1 || true

    # Run Lighthouse audit
    echo -e "${GREEN}2. Running Lighthouse accessibility audit...${NC}"

    docker run --rm \
        --network "$NETWORK" \
        -v "$(pwd)/$OUTPUT_DIR":/reports \
        femtopixel/google-lighthouse \
        "$BASE_URL/apps/$app" \
        --only-categories=accessibility \
        --output=json --output=html \
        --output-path="/reports/a11y-${app}-${TIMESTAMP}" \
        --chrome-flags="--headless --no-sandbox --disable-dev-shm-usage --disable-gpu" 2>&1 || true

    # Extract and display score
    JSON_REPORT="$OUTPUT_DIR/a11y-${app}-${TIMESTAMP}.report.json"
    if [[ -f "$JSON_REPORT" ]]; then
        SCORE=$(grep -oP '"accessibility":\s*\{\s*[^}]*"score":\s*\K[0-9.]+' "$JSON_REPORT" | head -1)
        if [[ -n "$SCORE" ]]; then
            SCORE_INT=$(echo "$SCORE * 100" | bc 2>/dev/null | cut -d. -f1 || echo "N/A")

            if [[ "$SCORE_INT" -ge 90 ]]; then
                echo -e "   Lighthouse Score: ${GREEN}${SCORE_INT}/100${NC}"
            elif [[ "$SCORE_INT" -ge 70 ]]; then
                echo -e "   Lighthouse Score: ${YELLOW}${SCORE_INT}/100${NC}"
            else
                echo -e "   Lighthouse Score: ${RED}${SCORE_INT}/100${NC}"
            fi
        fi
    fi

    echo ""
done

# Cleanup temporary test file
rm -f "$PLAYWRIGHT_TEST_FILE"

echo -e "${BLUE}========================================${NC}"
echo -e "${GREEN}Accessibility testing complete!${NC}"
echo -e "${BLUE}========================================${NC}"
echo ""
echo -e "Reports saved to: ${CYAN}$OUTPUT_DIR${NC}"
echo ""
echo -e "Files generated:"
ls -la "$OUTPUT_DIR"/*.json "$OUTPUT_DIR"/*.html "$OUTPUT_DIR"/*.png 2>/dev/null | awk '{print "  " $NF}'
